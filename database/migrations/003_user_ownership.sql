-- TubeTalk AI: per-user ownership (Supabase Auth). Run once in the Supabase SQL editor, after 002.
--
-- ADDITIVE ONLY: new tables, one new nullable column, indexes and read policies. No existing row is
-- changed or deleted. Existing chat sessions keep user_id = NULL, so they are visible to nobody until
-- a separately approved backfill assigns them to their owner.
--
-- Data model after this migration:
--   shared, reusable content (backend only): videos, transcript_chunks
--   per-user, private:                       user_videos (library), chat_sessions (+ messages),
--                                            user_video_insights
--   legacy, kept for the backfill only:      video_insights (no longer read or written by the app)

-- ------------------------------------------------------------- per-user library
-- A user can only open, chat about or get insights for videos in their own library. The video row
-- and its transcript chunks themselves are shared, so a video is fetched and embedded only once.
create table if not exists user_videos (
    user_id    uuid not null references auth.users(id) on delete cascade,
    video_id   uuid not null references videos(id) on delete cascade,
    created_at timestamptz not null default now(),
    primary key (user_id, video_id)
);
create index if not exists idx_user_videos_user_created on user_videos(user_id, created_at desc);
create index if not exists idx_user_videos_video on user_videos(video_id);

-- ------------------------------------------------------------- conversation owner
-- Nullable so the existing rows stay valid; the backend always sets it for new sessions.
alter table chat_sessions
    add column if not exists user_id uuid references auth.users(id) on delete cascade;
create index if not exists idx_chat_sessions_user_video
    on chat_sessions(user_id, video_id, updated_at desc);

-- ------------------------------------------------------------- per-user insights
-- Same columns as video_insights, one row per (user, video): one user's insights can never be read,
-- overwritten or regenerated by another user.
create table if not exists user_video_insights (
    user_id        uuid not null references auth.users(id) on delete cascade,
    video_id       uuid not null references videos(id) on delete cascade,
    status         varchar(20) not null default 'generating'
        check (status in ('generating', 'completed', 'failed')),
    summary        text,
    key_takeaways  jsonb,
    topics         jsonb,
    model          text,
    error_message  text,
    generated_at   timestamptz,
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),
    primary key (user_id, video_id)
);

drop trigger if exists trg_user_video_insights_updated_at on user_video_insights;
create trigger trg_user_video_insights_updated_at before update on user_video_insights
    for each row execute function set_updated_at();

-- ------------------------------------------------------------- RLS
-- The backend uses the service-role key (bypasses RLS) and enforces ownership itself. These
-- policies are the second line of defence for anyone using the public (anon/publishable) key:
--   * signed-in users may READ only their own rows;
--   * nobody may insert, update or delete through the public API (no write policies at all);
--   * the shared tables (videos, transcript_chunks) and the legacy video_insights keep no policies,
--     so they stay backend-only and never reveal what other users have processed.
alter table user_videos         enable row level security;
alter table user_video_insights enable row level security;
-- (videos, chat_sessions, chat_messages, transcript_chunks, video_insights: already enabled in 001/002)

drop policy if exists "own library rows" on user_videos;
create policy "own library rows" on user_videos
    for select to authenticated
    using (user_id = (select auth.uid()));

drop policy if exists "own chat sessions" on chat_sessions;
create policy "own chat sessions" on chat_sessions
    for select to authenticated
    using (user_id = (select auth.uid()));

drop policy if exists "messages of own chat sessions" on chat_messages;
create policy "messages of own chat sessions" on chat_messages
    for select to authenticated
    using (exists (
        select 1 from chat_sessions s
        where s.id = chat_messages.session_id and s.user_id = (select auth.uid())
    ));

drop policy if exists "own insights" on user_video_insights;
create policy "own insights" on user_video_insights
    for select to authenticated
    using (user_id = (select auth.uid()));

-- Let the Supabase API see the new tables and relationships right away.
notify pgrst, 'reload schema';
